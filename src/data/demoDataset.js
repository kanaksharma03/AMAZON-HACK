export function buildRegionGeoJsonLayers(regionId, sites) {
  const regionSites = sites.filter((s) => s.regionId === regionId);

  const catchmentFeatures = regionSites.map((site) => {
    const { lat, lon } = site.coordinates;
    const dLat = 0.009;
    const dLon = 0.011;
    return {
      type: 'Feature',
      properties: {
        id: `CATCH-${site.id}`,
        siteId: site.id,
        name: `${site.name} Recharge Catchment`,
        areaHa: site.terrainAndLithology.catchmentAreaHa,
        suitabilityCategory: site.suitabilityCategory,
        safetyPassed: site.safetyAssessment.passed,
      },
      geometry: {
        type: 'Polygon',
        coordinates: [
          [
            [lon - dLon * 0.8, lat + dLat * 0.4],
            [lon + dLon * 0.3, lat + dLat * 1.1],
            [lon + dLon * 1.0, lat + dLat * 0.2],
            [lon + dLon * 0.5, lat - dLat * 0.7],
            [lon - dLon * 0.6, lat - dLat * 0.5],
            [lon - dLon * 0.8, lat + dLat * 0.4],
          ],
        ],
      },
    };
  });

  const lineamentFeatures = regionSites.map((site, idx) => {
    const { lat, lon } = site.coordinates;
    const angleOffset = idx % 2 === 0 ? 0.016 : -0.014;
    return {
      type: 'Feature',
      properties: {
        id: `LIN-${site.id}`,
        siteId: site.id,
        type: idx % 2 === 0 ? 'Structural Lineament / Fracture Zone' : '2nd-Order Drainage Channel',
        lithology: site.terrainAndLithology.lithology,
      },
      geometry: {
        type: 'LineString',
        coordinates: [
          [lon - 0.018, lat - angleOffset],
          [lon - 0.003, lat + 0.001],
          [lon + 0.016, lat + angleOffset],
        ],
      },
    };
  });

  const heatZoneFeatures = regionSites
    .filter((s) => s.terrainAndLithology.lstAnomalyC >= 2.0)
    .map((site) => {
      const { lat, lon } = site.coordinates;
      const r = 0.013;
      return {
        type: 'Feature',
        properties: {
          id: `HEAT-${site.id}`,
          siteId: site.id,
          lstAnomalyC: site.terrainAndLithology.lstAnomalyC,
          label: `+${site.terrainAndLithology.lstAnomalyC}°C LST Anomaly Zone`,
        },
        geometry: {
          type: 'Polygon',
          coordinates: [
            [
              [lon - r, lat - r * 0.7],
              [lon + r, lat - r * 0.7],
              [lon + r * 0.9, lat + r * 0.8],
              [lon - r * 0.8, lat + r * 0.9],
              [lon - r, lat - r * 0.7],
            ],
          ],
        },
      };
    });

  return {
    catchments: { type: 'FeatureCollection', features: catchmentFeatures },
    lineaments: { type: 'FeatureCollection', features: lineamentFeatures },
    heatZones: { type: 'FeatureCollection', features: heatZoneFeatures },
  };
}
